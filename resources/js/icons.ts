export async function renderIcons() {
  const nodes = document.querySelectorAll<HTMLElement>('[data-lucide]');
  if (!nodes.length) return;
  // Survey sections may contain a custom icon name saved by an older client.
  const needsCustomIcon = Array.from(nodes).some((node) => {
    const name = (node.dataset.lucide ?? '').replace(/(^|[-_ ]+)(\w)/g, (_, _separator, char: string) =>
      char.toUpperCase(),
    );
    return !Object.prototype.hasOwnProperty.call(commonIcons, name);
  });
  const icons = needsCustomIcon ? await import('lucide/dist/esm/iconsAndAliases.mjs') : commonIcons;
  createIcons({ icons });
}
